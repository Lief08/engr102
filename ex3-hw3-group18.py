def celsius_to_fahrenheit(celsius_temp):
    """
    Takes in a temperature in Celsius and returns its equivalent measurement in Fahrenheit
    """
    return (celsius_temp * (9/5)) + 32

print(celsius_to_fahrenheit(100))
print(celsius_to_fahrenheit(1))
print(celsius_to_fahrenheit(4))
print(celsius_to_fahrenheit(-4))
print(celsius_to_fahrenheit(-1))
print(celsius_to_fahrenheit(-3))
print(celsius_to_fahrenheit(3))
print(celsius_to_fahrenheit(2))
print(celsius_to_fahrenheit(0))
print(celsius_to_fahrenheit(-5))
print(celsius_to_fahrenheit(-2))


